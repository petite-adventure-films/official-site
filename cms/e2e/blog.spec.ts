test('a failed blog save prevents duplication and an uncertain duplicate response reuses the operation', async ({ page, request }) => {
  await page.goto('/cms/blog/new');let copies = 0;
  page.on('request', r => { if (r.url().endsWith('/duplicate')) copies++; });
  await page.route('**/api/contents', route => route.request().method() === 'POST' ? route.abort() : route.continue());
  await page.getByRole('textbox', { name: 'タイトル', exact: true }).fill('失敗しても保持');
  await page.getByRole('button', { name: '複製', exact: true }).click();
  await expect(page.getByText('保存できなかったため、複製を中止しました。入力内容は残っています。')).toBeVisible();expect(copies).toBe(0);
  await page.unroute('**/api/contents');
  let copyId = '';let firstOperation = '';
  await page.route('**/duplicate', async route => { firstOperation = route.request().postDataJSON().operationId;const result = await route.fetch();copyId = (await result.json()).id;await route.abort(); });
  await page.getByRole('button', { name: '複製', exact: true }).click();await expect(page.getByRole('button', { name: '複製を再試行' })).toBeVisible();
  await page.unroute('**/duplicate');
  const retry = page.waitForRequest(r => r.url().endsWith('/duplicate'));
  await page.getByRole('button', { name: '複製を再試行' }).click();expect((await retry).postDataJSON().operationId).toBe(firstOperation);
  await expect(page).toHaveURL(new RegExp(`/cms/blog/${copyId}/edit$`));await expect(page.getByRole('textbox', { name: 'タイトル', exact: true })).toHaveValue('失敗しても保持');
  const result = await (await request.get('/api/contents?type=blog&q=' + encodeURIComponent('失敗しても保持'))).json();expect(result.count).toBe(2);
});
