import { expect, test } from '@playwright/test';
test('blog draft retains rich text, classification and switches when reopened from its own list', async ({ page, request }) => {
  await page.goto('/cms/blog/new');
  await page.getByRole('textbox', { name: 'タイトル', exact: true }).fill('ブログ保存の確認');
  const body = page.getByRole('textbox', { name: '本文', exact: true });
  await body.fill('本文だけの検索語');
  await body.press('ControlOrMeta+a');
  await page.getByRole('button', { name: '太字', exact: true }).click();
  await page.getByRole('button', { name: '雑木林コラム', exact: true }).click();
  await page.getByRole('switch', { name: 'おすすめ', exact: true }).check();
  await page.getByRole('switch', { name: 'ワークショップ報告', exact: true }).check();
  await page.getByRole('button', { name: 'インド日記', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('保存済み');
  const id = page.url().split('/').at(-2)!;
  const saved = await (await request.get(`/api/contents/${id}`)).json();
  expect(saved.type).toBe('blog');expect(saved.payload.isRecommended).toBe(true);expect(saved.payload.categoryId).toBe('2879');
  expect(saved.payload.body.doc.content[0].content[0].marks).toContainEqual({ type: 'bold' });
  await expect(page.getByRole('button', { name: '公開', exact: true })).toBeDisabled();
  await page.reload();await expect(body).toHaveText('本文だけの検索語');await expect(body.locator('strong')).toHaveText('本文だけの検索語');
  await expect(page.getByRole('switch', { name: 'おすすめ', exact: true })).toBeChecked();
  await expect(page.getByRole('button', { name: 'インド日記', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await body.click();await body.press('End');await body.press('Enter');await body.pressSequentially('再編集した本文');
  await expect(page.getByRole('status')).toHaveText('保存済み');
  await page.getByText('ブログ一覧', { exact: true }).click();
  await page.getByLabel('キーワード検索').fill('再編集した本文');await page.getByLabel('キーワード検索').press('Enter');
  await page.getByRole('link', { name: 'ブログ保存の確認', exact: true }).click();await expect(body).toContainText('再編集した本文');
  await page.screenshot({ path: 'test-results/blog-editor.png', fullPage: true });
  const events = await (await request.get('/api/contents?type=event&q=' + encodeURIComponent('再編集した本文'))).json();expect(events.count).toBe(0);
  await page.goto(`/cms/events/${id}/edit`);await expect(page.getByRole('alert')).toContainText('読み込めませんでした');
});
test('headings, lists and safe links survive a save and reload', async ({ page, request }) => {
  await page.goto('/cms/blog/new');
  const body = page.getByRole('textbox', { name: '本文', exact: true });
  await body.fill('見出しの文');
  await page.getByRole('button', { name: '段落・見出し' }).click();
  await page.getByRole('menuitem', { name: '見出し2' }).click();
  await body.press('End');await body.press('Enter');
  await page.getByRole('button', { name: '段落・見出し' }).click();await page.getByRole('menuitem', { name: '段落', exact: true }).click();
  await body.pressSequentially('リンクの文');for (let i = 0; i < 5; i++) await body.press('Shift+ArrowLeft');
  expect(await page.evaluate(() => window.getSelection()?.toString())).toBe('リンクの文');
  await page.getByRole('button', { name: 'リンク', exact: true }).click();
  await page.getByRole('textbox', { name: 'リンク先URL' }).fill('javascript:alert(1)');
  await expect(page.getByRole('button', { name: '適用' })).toBeDisabled();
  await page.getByRole('textbox', { name: 'リンク先URL' }).fill('https://example.com/document.pdf');await page.getByRole('button', { name: '適用' }).click();
  await expect(body.locator('a')).toHaveAttribute('href', 'https://example.com/document.pdf');
  await page.getByRole('button', { name: '箇条書き' }).click();
  await expect(page.getByRole('status')).toHaveText('保存済み');
  const id = page.url().split('/').at(-2)!;
  const original = await (await request.get(`/api/contents/${id}`)).json();
  await page.reload();await expect(body.locator('h2')).toHaveText('見出しの文');
  await expect(body.locator('ul li a')).toHaveAttribute('href', 'https://example.com/document.pdf');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  expect((await (await request.get(`/api/contents/${id}`)).json()).payload.body).toEqual(original.payload.body);
});
