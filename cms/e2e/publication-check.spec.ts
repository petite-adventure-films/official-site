import { expect, test } from '@playwright/test';
test('checks current saved inputs, focuses errors and never publishes', async ({ page, request }) => {
  await page.goto('/cms/events/new');
  const mutations: string[] = [];
  page.on('request', req => { if (['POST', 'PUT', 'DELETE'].includes(req.method())) mutations.push(new URL(req.url()).pathname); });
  await page.getByRole('button', { name: '公開前チェック', exact: true }).click();
  const title = page.getByRole('textbox', { name: 'タイトル', exact: true });
  await expect(page.getByText('入力内容を確認してください。下書きは保存されています。')).toBeVisible();
  await expect(title).toBeFocused(); await expect(title).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByText('タイトルを入力してください。', { exact: true })).toBeVisible();
  const id = page.url().split('/').at(-2)!;
  await title.fill('チェックする記事');
  await expect(page.getByText('入力内容を確認してください。下書きは保存されています。')).toHaveCount(0);
  await page.getByRole('textbox', { name: '開催日', exact: true }).fill('2026-12-30');
  await page.getByRole('button', { name: 'オフライン', exact: true }).click();
  await page.getByRole('button', { name: '公開前チェック', exact: true }).click();
  await expect(page.getByRole('group', { name: '開催形式 *', exact: true })).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByText('開催形式を選択してください。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'オンライン', exact: true }).click();
  await page.getByRole('button', { name: '公開前チェック', exact: true }).click();
  await expect(page.getByText('入力内容に問題は見つかりませんでした。公開は行っていません。')).toBeVisible();
  expect((await (await request.get(`/api/contents/${id}`)).json()).payload.title).toBe('チェックする記事');
  expect(mutations.every(path => path === '/api/contents' || path === `/api/contents/${id}` || path === `/api/contents/${id}/check-publication`)).toBe(true);
  await title.fill('編集再開');
  await expect(page.getByText('入力内容に問題は見つかりませんでした。公開は行っていません。')).toHaveCount(0);
});
test('failed saving does not check; network failure can be retried without losing input', async ({ page }) => {
  await page.goto('/cms/events/new'); let checks = 0;
  page.on('request', req => { if (req.url().endsWith('/check-publication')) checks++; });
  await page.route('**/api/contents', route => route.request().method() === 'POST' ? route.abort() : route.continue());
  await page.getByRole('textbox', { name: 'タイトル', exact: true }).fill('入力を保持');
  await page.getByRole('button', { name: '公開前チェック', exact: true }).click();
  await expect(page.getByText('保存できなかったため、公開前チェックを中止しました。入力内容は残っています。')).toBeVisible();
  expect(checks).toBe(0);
  await page.unroute('**/api/contents');
  await page.route('**/check-publication', route => route.abort());
  await page.getByRole('button', { name: '公開前チェック', exact: true }).click();
  await expect(page.getByText('公開前チェックができませんでした。入力内容は残っています。ログイン状態と通信を確認して再度チェックしてください。')).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'タイトル', exact: true })).toHaveValue('入力を保持');
  await page.unroute('**/check-publication');
  await page.getByRole('button', { name: '公開前チェック', exact: true }).click();
  await expect(page.getByText('有効な開催日を入力してください。', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/publication-check-1440.png', fullPage: true });
});
